FACE_ONLY_PROPS = None  # filled lazily from the rig


def apply_expression(name, rig=None, keyframe=False, frame=None, head=True):
    rig = rig or bpy.data.objects["BOB_Rig"]
    ctrl = rig.pose.bones["CTRL_face"]
    expr = EXPRESSIONS[name]
    for k in list(ctrl.keys()):
        if k.startswith("hand_"):
            continue
        if isinstance(ctrl[k], float):
            ctrl[k] = float(expr.get(k, 0.0))
            if keyframe:
                ctrl.keyframe_insert(f'["{k}"]', frame=frame or bpy.context.scene.frame_current)
    if head:
        hb = rig.pose.bones["head"]
        hb.rotation_mode = "XYZ"
        nod, turn, tilt = expr.get("_head", (0, 0, 0))
        hb.rotation_euler = (math.radians(-nod), math.radians(turn), math.radians(tilt))
        if keyframe:
            hb.keyframe_insert("rotation_euler", frame=frame or bpy.context.scene.frame_current)
    bpy.context.view_layer.update()


UI_TEMPLATE = '''# Bob expression panel - auto-generated by build_expressions.py
# Adds a "Bob" tab to the 3D viewport sidebar (press N).
import math
import bpy

EXPRESSIONS = {expressions!r}
ORDER = {order!r}


def apply(name, keyframe):
    rig = bpy.data.objects.get("BOB_Rig")
    if rig is None:
        return
    ctrl = rig.pose.bones["CTRL_face"]
    expr = EXPRESSIONS[name]
    f = bpy.context.scene.frame_current
    for k in list(ctrl.keys()):
        if k.startswith("hand_") or not isinstance(ctrl[k], float):
            continue
        ctrl[k] = float(expr.get(k, 0.0))
        if keyframe:
            ctrl.keyframe_insert('["%s"]' % k, frame=f)
    hb = rig.pose.bones["head"]
    hb.rotation_mode = "XYZ"
    nod, turn, tilt = expr.get("_head", (0, 0, 0))
    hb.rotation_euler = (math.radians(-nod), math.radians(turn), math.radians(tilt))
    if keyframe:
        hb.keyframe_insert("rotation_euler", frame=f)


class BOB_OT_expression(bpy.types.Operator):
    bl_idname = "bob.expression"
    bl_label = "Apply Bob Expression"
    bl_options = {{"REGISTER", "UNDO"}}
    name: bpy.props.StringProperty()

    def execute(self, context):
        apply(self.name, context.scene.get("bob_key_expressions", False))
        return {{"FINISHED"}}


class BOB_PT_panel(bpy.types.Panel):
    bl_space_type = "VIEW_3D"
    bl_region_type = "UI"
    bl_category = "Bob"
    bl_label = "Bob Expressions"

    def draw(self, context):
        lay = self.layout
        lay.prop(context.scene, '["bob_key_expressions"]', text="Keyframe on click")
        grid = lay.grid_flow(columns=2, even_columns=True)
        for n in ORDER:
            grid.operator("bob.expression", text=n).name = n
        rig = bpy.data.objects.get("BOB_Rig")
        if rig:
            box = lay.box()
            box.label(text="IK / FK")
            for p in ("arm_ik_L", "arm_ik_R", "leg_ik_L", "leg_ik_R"):
                box.prop(rig, '["%s"]' % p, slider=True)
            box = lay.box()
            box.label(text="Face sliders (CTRL_face)")
            ctrl = rig.pose.bones["CTRL_face"]
            for k in ctrl.keys():
                if isinstance(ctrl[k], float):
                    box.prop(ctrl, '["%s"]' % k, slider=True)


classes = (BOB_OT_expression, BOB_PT_panel)


def register():
    for c in classes:
        try:
            bpy.utils.register_class(c)
        except ValueError:
            pass


if __name__ == "__main__":
    register()
'''


def write_ui():
    code = UI_TEMPLATE.format(expressions=EXPRESSIONS, order=EXPRESSION_ORDER)
    txt = bpy.data.texts.get("bob_expressions_ui.py") or bpy.data.texts.new("bob_expressions_ui.py")
    txt.clear()
    txt.write(code)
    txt.use_module = True       # registers on file load when scripts are trusted
    bpy.context.scene["bob_key_expressions"] = False
    try:
        exec(compile(code, "bob_expressions_ui.py", "exec"), {"__name__": "__main__"})
    except Exception as exc:
        print("[bob] UI registration skipped:", exc)


def build(M=None):
    write_ui()
    apply_expression("Neutral")


if __name__ == "__main__":
    build()
